/**
 * `pnpm brand:gen`: everything the platforms show of the brand, derived from the AI-drawn master icon
 * (brand/app-icon-master-1024.png) and brand.config.json, with the Chromium of @playwright/test:
 *
 * - brand/app-icon.svg and app-icon-maskable.svg: the master embedded as WebP (the maskable one full-bleed on the
 *   edge colour of the artwork, the art inside the 80% safe zone), the sources @achoo254/brand draws from;
 * - brand/generated/: web manifest, PNG icons, favicon.ico (writeBrandFiles);
 * - apps/web/public/og-image.png: the 1200 × 630 link preview: the master art beside the name and the description,
 *   which are drawn here as text in the app's own font (never by the AI).
 *
 * Run after changing the master or the brand, then commit the files.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
import { chromiumRenderer, writeBrandFiles } from '@achoo254/brand/build';
import { primaryOrigin } from '@achoo254/brand/hosts';
import { type Page, chromium } from '@playwright/test';
import { BRAND_GENERATED_DIR, BRAND_ROOT, MANIFEST_OPTIONS, OG_IMAGE, loadChuanhoBrand } from '../apps/web/vite-brand';

const MASTER = new URL('brand/app-icon-master-1024.png', BRAND_ROOT);
/** The violet at the edge of the artwork, behind the maskable icon so the art can sit inside the safe zone. */
const TILE = '#3a2c6c';
const ICON_LICENCE = 'AI-generated with open models (Qwen-Image; Apache-2.0) for the hoandat ecosystem; owned by hoandat, all rights reserved (not CC0)';
/** Sunset purple, temple gold and warm cream of the app (apps/web/src/ui/tokens.css). */
const OG_COLORS = { deep: '#1d0f33', violet: '#4a2a6e', glow: '#a04a7c', text: '#fbf1e2', muted: '#d6c6e8', gold: '#f0c978' };

const webRequire = createRequire(new URL('apps/web/package.json', BRAND_ROOT));

/** A @fontsource weight stylesheet with its WOFF2 files inlined, so the page renders offline. */
function inlinedFontCss(stylesheet: string): string {
  const file = webRequire.resolve(stylesheet);
  return readFileSync(file, 'utf8').replace(/url\(\.\/files\/([^)]+\.woff2)\) format\('woff2'\)(, url\([^)]+\) format\('woff'\))?/g, (_match, name: string) => {
    const bytes = readFileSync(new URL(`files/${name}`, pathToFileURL(file)));
    return `url(data:font/woff2;base64,${bytes.toString('base64')}) format('woff2')`;
  });
}

/** The master scaled to `size` px and encoded by the browser, as a data URL. */
async function encodeMaster(page: Page, masterDataUrl: string, size: number, type: 'image/webp' | 'image/png'): Promise<string> {
  return page.evaluate(
    async ({ src, size, type }) => {
      const image = new Image();
      image.src = src;
      await image.decode();
      const canvas = document.createElement('canvas');
      canvas.width = size;
      canvas.height = size;
      const context = canvas.getContext('2d');
      if (!context) throw new Error('no 2d context');
      context.imageSmoothingQuality = 'high';
      context.drawImage(image, 0, 0, size, size);
      return canvas.toDataURL(type, 0.92);
    },
    { src: masterDataUrl, size, type },
  );
}

const iconSvg = (webpDataUrl: string, appName: string): string =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><!-- ${appName} app icon: ${ICON_LICENCE}. Generated by pnpm brand:gen from brand/app-icon-master-1024.png. --><image width="1024" height="1024" href="${webpDataUrl}"/></svg>\n`;

const maskableSvg = (webpDataUrl: string, background: string, appName: string): string =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024"><!-- Maskable ${appName} app icon: ${ICON_LICENCE}. Generated by pnpm brand:gen. --><rect width="1024" height="1024" fill="${background}"/><image x="102" y="102" width="820" height="820" href="${webpDataUrl}"/></svg>\n`;

function ogHtml(iconDataUrl: string, appName: string, description: string, host: string): string {
  const c = OG_COLORS;
  return `<!doctype html><html lang="vi"><head><style>
${inlinedFontCss('@fontsource/be-vietnam-pro/400.css')}
${inlinedFontCss('@fontsource/be-vietnam-pro/800.css')}
</style></head><body style="margin:0">
<div style="position:relative;width:${OG_IMAGE.width}px;height:${OG_IMAGE.height}px;overflow:hidden;color:${c.text};font-family:'Be Vietnam Pro',sans-serif;background:radial-gradient(ellipse 60% 80% at 20% 15%,${c.violet},transparent 70%),radial-gradient(ellipse 60% 70% at 40% 105%,${c.glow},transparent 70%),${c.deep}">
<img src="${iconDataUrl}" alt="" style="position:absolute;top:0;right:0;width:${OG_IMAGE.height}px;height:${OG_IMAGE.height}px;-webkit-mask-image:linear-gradient(to right,transparent,#000 30%)">
<div style="position:absolute;top:0;bottom:0;left:0;width:700px;box-sizing:border-box;padding:0 30px 0 80px;display:flex;flex-direction:column;justify-content:center;gap:22px">
<div style="font-weight:800;font-size:112px;line-height:1;color:${c.gold};text-shadow:0 0 34px rgba(240,201,120,.35)">${appName}</div>
<div style="font-size:34px;line-height:1.4">${description}</div>
<div style="font-size:26px;font-weight:800;color:${c.muted}"><span style="color:${c.gold}">&#10022;</span> ${host}</div>
</div></div></body></html>`;
}

async function main(): Promise<void> {
  const brand = loadChuanhoBrand();
  const masterDataUrl = `data:image/png;base64,${readFileSync(MASTER).toString('base64')}`;
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage({ deviceScaleFactor: 1 });
    const webp512 = await encodeMaster(page, masterDataUrl, 512, 'image/webp');
    writeFileSync(new URL(brand.icon, BRAND_ROOT), iconSvg(webp512, brand.appName));
    writeFileSync(new URL(brand.iconMaskable, BRAND_ROOT), maskableSvg(webp512, TILE, brand.appName));

    await page.setViewportSize({ width: OG_IMAGE.width, height: OG_IMAGE.height });
    const og = await encodeMaster(page, masterDataUrl, OG_IMAGE.height, 'image/png');
    await page.setContent(ogHtml(og, brand.appName, 'Gõ mõ, thắp hương, bớt khẩu nghiệp. Chơi cho tâm bớt lag.', new URL(primaryOrigin(brand)).host));
    await page.locator('img').evaluateAll((images: HTMLImageElement[]) => Promise.all(images.map((img) => img.decode())));
    await page.evaluate(() => document.fonts.ready);
    writeFileSync(new URL(`apps/web/public/${OG_IMAGE.path}`, BRAND_ROOT), await page.screenshot({ clip: { x: 0, y: 0, width: OG_IMAGE.width, height: OG_IMAGE.height } }));
  } finally {
    await browser.close();
  }
  const written = await writeBrandFiles({
    brand,
    root: BRAND_ROOT,
    generatedDir: BRAND_GENERATED_DIR,
    manifests: MANIFEST_OPTIONS,
    indent: 2,
    renderer: chromiumRenderer(chromium),
  });
  console.log(`Wrote brand SVGs, og-image and ${written.length} files to brand/generated/: ${written.join(', ')}`);
}

main().catch((error: unknown) => {
  console.error('brand:gen failed:', error);
  process.exitCode = 1;
});
